const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "../src/lib/i18n/messages");

function parseObj(src) {
  const obj = {};
  const re = /"([^"]+)":\s*("(?:\\.|[^"\\])*"|`(?:\\.|[^`\\])*`)/gs;
  let m;
  while ((m = re.exec(src))) {
    let val = m[2];
    if (val.startsWith("`")) val = val.slice(1, -1).replace(/\\n/g, "\n").replace(/\\`/g, "`");
    else val = JSON.parse(val);
    obj[m[1]] = val;
  }
  return obj;
}

function esc(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
}

function writeLocale(id, base, overrides) {
  const messages = { ...base, ...overrides };
  const keys = Object.keys(fr);
  const lines = keys.map((k) => `  "${k}": "${esc(messages[k] ?? fr[k])}",`);
  const out = `import type { Messages } from "./fr";\n\nexport const ${id}: Messages = {\n${lines.join("\n")}\n};\n`;
  fs.writeFileSync(path.join(dir, `${id}.ts`), out, "utf8");
}

